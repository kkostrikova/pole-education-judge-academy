/* Людські повідомлення замість кодів помилок.
 *
 * Функції бази кидають винятки короткими кодами — INVALID_SIGNATURE_SIZE,
 * NO_ATTEMPTS_LEFT і такі інші. Supabase віддає їх у error.message як є, і
 * сторінки показували їх студентові просто так: «Не вдалося підписати
 * договір: INVALID_SIGNATURE_SIZE». Людина, яка це бачить, не знає ні що
 * сталося, ні що робити — і здається. Саме так виглядає «сайт не працює».
 *
 * Тут один словник на весь сайт. Технічний текст не губиться — він іде в
 * консоль браузера, щоб було що подивитись, якщо доведеться розбиратись.
 */
(() => {
  const MESSAGES = {
    AUTH_REQUIRED:
      'Сесія завершилася. Увійдіть у свій акаунт ще раз і повторіть дію.',
    ADMIN_REQUIRED:
      'Ця дія доступна лише адміністраторам курсу.',

    /* підпис договору */
    CONSENT_REQUIRED:
      'Щоб підписати договір, поставте галочку згоди під текстом.',
    INVALID_FULL_NAME:
      'Вкажіть повне імʼя та прізвище — щонайменше дві літери.',
    INVALID_SIGNATURE:
      'Підпис не вдалося зберегти. Намалюйте його ще раз у рамці для підпису.',
    INVALID_SIGNATURE_SIZE:
      'Підпис не вдалося зберегти. Натисніть «Очистити» і намалюйте його ще раз.',

    /* іспити */
    EXAM_CLOSED:
      'Іспит зараз закритий. Він відкриється, коли адміністратор курсу його запустить.',
    EXAM_NOT_FOUND:
      'Не вдалося знайти цей іспит. Поновіть сторінку, а якщо не допоможе — напишіть адміністратору курсу.',
    NO_ATTEMPTS_LEFT:
      'Спроби вичерпано. Щоб скласти іспит ще раз, попросіть адміністратора курсу відкрити нову спробу.',
    ATTEMPT_NOT_FOUND:
      'Не вдалося знайти цю спробу. Поновіть сторінку.',
    ATTEMPT_STILL_IN_PROGRESS:
      'Спроба ще триває — її не можна перевіряти, доки іспит не завершено.',
    ATTEMPT_NOT_SUBMITTED:
      'Іспит ще не надіслано на перевірку.',
    RESULT_ALREADY_PUBLISHED:
      'Результат уже опубліковано — змінити його не можна.',
    QUESTION_NOT_MANUAL:
      'Це питання перевіряється автоматично, оцінку вручну поставити не можна.',
    INVALID_POINTS:
      'Невірна кількість балів.',

    /* сертифікат */
    INVALID_CERTIFICATE_NAME:
      'Перевірте, як написане імʼя для сертифіката — потрібні щонайменше дві літери.',
    INVALID_ENGLISH_CERTIFICATE_NAME:
      'Імʼя для англійської версії сертифіката пишеться латинськими літерами.',
    CERTIFICATE_ALREADY_ISSUED:
      'Сертифікат уже видано. Щоб змінити дані в ньому, зверніться до адміністратора курсу.',
    AUTO_KEY_NOT_READY:
      'Сертифікат ще готується. Спробуйте за хвилину.',

    /* архів і видалення студента */
    STUDENT_NOT_FOUND:
      'Такого студента вже немає в базі. Поновіть сторінку.',
    CANNOT_ARCHIVE_SELF:
      'Себе архівувати не можна.',
    CANNOT_DELETE_SELF:
      'Себе видалити не можна.',
    CANNOT_ARCHIVE_ADMIN:
      'Адміністратора архівувати не можна.',
    CANNOT_DELETE_ADMIN:
      'Адміністратора видалити не можна.',
    NAME_MISMATCH:
      'Імʼя не збігається з тим, що записане в профілі. Перевірте й спробуйте ще раз.',
    ACCOUNT_ARCHIVED:
      'Цей акаунт в архіві — доступ до курсу закрито. Зверніться до адміністратора курсу.'
  };

  /* Supabase Auth відповідає своїми фразами англійською — вхід і реєстрація
     показували їх студентові як є. Збігаємо за характерним шматком тексту;
     те, що не впізнали, піде у загальну фразу нижче. */
  const AUTH = [
    [/invalid login credentials/i,
      'Невірна пошта або пароль. Перевірте ще раз.'],
    [/email not confirmed/i,
      'Пошту ще не підтверджено. Відкрийте лист від нас і перейдіть за посиланням.'],
    [/user already registered|already been registered/i,
      'Акаунт із такою поштою вже існує. Увійдіть замість реєстрації або відновіть пароль.'],
    [/password should be at least (\d+)/i,
      'Пароль закороткий — потрібно щонайменше $1 символів.'],
    [/unable to validate email address|invalid format/i,
      'Перевірте, чи правильно написана адреса пошти.'],
    [/for security purposes.*?(\d+) seconds/i,
      'Забагато спроб поспіль. Зачекайте $1 секунд і спробуйте ще раз.'],
    [/email rate limit exceeded|over_email_send_rate_limit/i,
      'Забагато листів за короткий час. Зачекайте кілька хвилин і спробуйте ще раз.'],
    [/signups not allowed|signup is disabled/i,
      'Реєстрація зараз закрита. Напишіть адміністратору курсу.']
  ];

  /* Відповіді самого PostgREST і Postgres. Без них адміністратор бачить
     загальну фразу там, де причина цілком конкретна: функції ще немає в
     базі, бо SQL-патч не запускали, або колонки немає, бо запустили не
     весь файл. Це повідомлення для того, хто може це виправити. */
  const SERVER = [
    [/PGRST202|could not find the function|schema cache/i,
      'Цієї функції ще немає в базі. Запустіть SQL-патч у Supabase → SQL Editor, '
      + 'тоді кнопка запрацює.'],
    [/42883|function .* does not exist/i,
      'Функції немає в базі. Запустіть SQL-патч у Supabase → SQL Editor.'],
    [/42703|column .* does not exist/i,
      'У базі бракує колонки — схоже, SQL-патч виконався не повністю. '
      + 'Запустіть його ще раз цілком.'],
    [/PGRST301|JWT expired|invalid claim/i,
      'Сесія завершилася. Увійдіть ще раз.'],
    [/permission denied/i,
      'Бракує прав на цю дію в базі. Перевірте, що ви зайшли під акаунтом адміністратора.']
  ];

  /* Обрив звʼязку виглядає інакше: це не код з бази, а помилка самого
     запиту. Її варто відрізняти — студент має зрозуміти, що справа в
     інтернеті, а не в тому, що він щось зробив не так. */
  const OFFLINE = /failed to fetch|networkerror|load failed|network request failed|err_internet|timeout/i;

  const CODES_BY_LENGTH = Object.keys(MESSAGES).sort((a, b) => b.length - a.length);

  function text(err, fallback) {
    const fb = fallback || 'Не вдалося виконати дію. Спробуйте ще раз.';
    if (!err) return fb;

    /* PostgREST кладе підказку то в message, то в code, то в details —
       дивимось на все разом, щоб не проґавити справжню причину. */
    const raw = [err.message, err.code, err.details, err.hint, err.error_description]
      .filter(Boolean).join(' | ') || String(err);
    if (raw) console.warn('[PE] технічна помилка:', raw, err);

    /* Найдовші коди спершу: INVALID_SIGNATURE є початком
       INVALID_SIGNATURE_SIZE, і за порядком оголошення коротший перехопив
       би повідомлення, призначене довшому. */
    for (const code of CODES_BY_LENGTH) {
      if (raw.includes(code)) return MESSAGES[code];
    }
    for (const [pattern, phrase] of AUTH) {
      const hit = raw.match(pattern);
      if (hit) return phrase.replace('$1', hit[1] || '');
    }
    for (const [pattern, phrase] of SERVER) {
      if (pattern.test(raw)) return phrase;
    }
    if (OFFLINE.test(raw)) {
      return 'Немає звʼязку з сервером. Перевірте інтернет і спробуйте ще раз.';
    }
    return fb;
  }

  window.PE_errorText = text;
})();
