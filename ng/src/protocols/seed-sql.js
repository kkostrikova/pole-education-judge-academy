import { PROTOCOLS } from './index.js';

const lit = (v) => {
  if (v === undefined || v === null) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};

export function protocolSeedSql() {
  const rows = [];
  for (const p of Object.values(PROTOCOLS)) {
    for (const s of p.sections) {
      for (const i of s.items) {
        rows.push(`  (${[p.key, i.key, i.type, i.max, i.min, i.step, i.points, i.only?.join(','), !!i.requiresComment]
          .map(lit).join(', ')})`);
      }
    }
  }
  return [
    '-- GENERATED by scripts/gen-protocol-seed.mjs from src/protocols. Do not edit by hand.',
    'delete from protocol_items;',
    'insert into protocol_items (protocol_key, item_key, type, max, min, step, points, only_apparatus, requires_comment) values',
    rows.join(',\n') + ';',
    '',
  ].join('\n');
}
